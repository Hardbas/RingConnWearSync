package io.github.hardbas.wearsync.bridge.service

import android.util.Log
import io.github.hardbas.wearsync.bridge.data.RingConnVitals
import java.time.ZoneId
import java.time.ZonedDateTime
import kotlin.math.roundToInt

object RingConnTelemetryParser {
    private const val TAG = "RingConnParser"

    // Regex matchers for units / composite tokens
    private val TIME_STRING_REGEX = Regex("""(?i)\b([0-9]|0[0-9]|1[0-9]|2[0-3]):([0-5][0-9])(?:\s*([ap]\.?\s*m\.?))?\b""")
    private val AMPM_STANDALONE_REGEX = Regex("""(?i)^([ap]\.?\s*m\.?)$""")
    private val VITAL_SIGNS_REGEX = Regex("""(?i)\b(\d{2,3})\s*bpm\s+(\d{2,3})\s*%\s+(\d{1,3})\s*ms\b""")
    private val HR_BPM_REGEX = Regex("""(?i)\b(\d{2,3})\s*(?:bpm|lpm)\b""")
    // SpO2 is read through two anchored paths below: a `spo2`/`oxygen` header followed by
    // its number, and the `[.., bpm, 93, %, 59, ms]` triple. An unanchored percentage regex
    // used to live here and was never read; it is gone so nobody reintroduces the idea that
    // any 80-100% in the widget is blood oxygen.
    private val HRV_MS_REGEX = Regex("""(?i)\b(\d{1,3})\s*ms\b""")

    // Composite contentDescription regexes generated by RingConn Glance HomeAppWidget
    private val COMPOSITE_SLEEP_REGEX = Regex("""(?i)^(?:sleep|sueño)\s+(\d{1,3})$""")
    private val COMPOSITE_ACT_REGEX = Regex("""(?i)^(?:activity|actividad)\s+(\d{1,3})$""")
    private val COMPOSITE_STRESS_REGEX = Regex("""(?i)^(?:stress|estrés|estres)\s+(\d{1,3})$""")
    private val COMPOSITE_BAT_REGEX = Regex("""(?i)^(?:battery|batería|bateria)\s+(?:%)?(\d{1,3})(?:%)?$""")
    private val BASELINE_TEMP_REGEX = Regex("""(?i)\b(3[4-9](?:[.,]\d{1,2})?|40(?:[.,]0)?)\s*°?\s*C?\b""")
    private val REM_REGEX = Regex("""(?i)\brem\b""")
    private val SLEEP_DURATION_REGEX = Regex("""(?i)\b(\d{1,2})\s*h(?:rs?|oras?)?\s*(\d{1,2})\s*m(?:in(?:s|utos)?)?\b""")

    fun parseDurationMinutes(text: String?): Int? {
        if (text.isNullOrBlank()) return null
        val hm = SLEEP_DURATION_REGEX.find(text)
        if (hm != null) {
            val h = hm.groupValues[1].toIntOrNull() ?: 0
            val m = hm.groupValues[2].toIntOrNull() ?: 0
            return h * 60 + m
        }
        val hOnly = Regex("""(?i)\b(\d{1,2})\s*h(?:rs?|oras?)?\b""").find(text)
        if (hOnly != null && !text.contains("bpm", ignoreCase = true) && !text.contains("km", ignoreCase = true)) {
            val h = hOnly.groupValues[1].toIntOrNull()
            if (h != null && h in 1..14) return h * 60
        }
        val mOnly = Regex("""(?i)\b(\d{1,3})\s*m(?:in(?:s|utos)?)?\b""").find(text)
        if (mOnly != null && !text.contains("bpm", ignoreCase = true) && !text.contains("ms", ignoreCase = true) && !text.contains("km", ignoreCase = true)) {
            val m = mOnly.groupValues[1].toIntOrNull()
            if (m != null && m in 1..840) return m
        }
        return null
    }

    private val IGNORED_TITLES = setOf(
        "health score and battery level",
        "here's your health score and battery level",
        "vital signs",
        "steps and calories",
        "here's your steps and calories"
    )

    /**
     * Parses a list of strings extracted from an AppWidgetHostView or an AccessibilityNode tree.
     * Merges non-zero extracted values with [baseVitals].
     */
    fun parseTokens(tokens: List<String>, baseVitals: RingConnVitals): RingConnVitals {
        var sleepScore = baseVitals.sleepScore
        var sleepDeepMins = baseVitals.sleepDeepMins
        var sleepRemMins = baseVitals.sleepRemMins
        var sleepLightMins = baseVitals.sleepLightMins
        var sleepAwakeMins = baseVitals.sleepAwakeMins
        var parsedDeep = 0
        var parsedRem = 0
        var parsedLight = 0
        var parsedAwake = 0
        var activityScore = baseVitals.activityScore
        var stressScore = baseVitals.stressScore
        var lastHr = baseVitals.lastHeartRate
        var avgHr = baseVitals.avgHeartRate
        var lastSpo2 = baseVitals.lastSpo2
        var avgSpo2 = baseVitals.avgSpo2
        var lastHrv = baseVitals.lastHrv
        var avgHrv = baseVitals.avgHrv
        var liveSteps = baseVitals.liveSteps
        var targetSteps = baseVitals.targetSteps
        var liveCalorie = baseVitals.liveCalorie
        var targetCalorie = baseVitals.targetCalorie
        var ringBattery = baseVitals.ringBattery
        // A value stored before this guard existed may be garbage: start from a
        // sanitised copy so one bad scrape cannot survive every later parse.
        var skinTempOffset = SkinTemperatureGuard.sanitizeOffset(baseVitals.skinTempOffset)
        var skinTempBaseline = SkinTemperatureGuard.sanitizeBaseline(baseVitals.skinTempBaseline)
        var sleepInsight = baseVitals.sleepInsight
        var stressInsight = baseVitals.stressInsight
        var activityInsight = baseVitals.activityInsight
        var vitalsInsight = baseVitals.vitalsInsight

        // Split multiple lines and clean whitespace
        val cleanTokens = tokens.flatMap { it.split("\n", "\r") }
            .map { it.trim() }
            .filter { it.isNotEmpty() }

        val fullText = cleanTokens.joinToString(" ")

        // 1. Check for DataIndicatorsWidget exact triple (HR bpm, SpO2 %, HRV ms)
        VITAL_SIGNS_REGEX.find(fullText)?.let {
            val hr = it.groupValues[1].toIntOrNull()
            val spo2 = it.groupValues[2].toIntOrNull()
            val hrv = it.groupValues[3].toIntOrNull()
            if (hr != null && hr in 35..220) lastHr = hr
            if (spo2 != null && spo2 in 75..100) lastSpo2 = spo2
            if (hrv != null && hrv in 10..250) lastHrv = hrv
        }

        var parsedWidgetTimestamp: Long? = null

        // 2. Token-by-token contextual parsing
        for (i in cleanTokens.indices) {
            val token = cleanTokens[i]
            val lower = token.lowercase()

            if (IGNORED_TITLES.contains(lower) || lower.startsWith("unsupported size")) {
                continue
            }

            // --- Natural Language Insight Detection ---
            if (token.length in 28..240 && token.contains(' ') && !lower.startsWith("http")) {
                val sleepKeywords = listOf("sleep", "sueño", "deep", "rest", "descanso", "bedtime", "recovery", "recuperación")
                val stressKeywords = listOf("stress", "estrés", "estres", "relax", "relaj", "autonomic", "nervous", "tensión", "calma")
                val actKeywords = listOf("activity", "actividad", "steps", "pasos", "calori", "exercise", "ejercicio", "move", "movimiento")
                val vitalsKeywords = listOf("heart", "frecuencia", "spo2", "oxygen", "oxígeno", "hrv", "temp", "vital", "baseline")

                val hasExplicitSleep = listOf("sleep", "sueño", "deep", "descanso", "bedtime", "recovery", "recuperación").any { lower.contains(it) } || REM_REGEX.containsMatchIn(token)

                when {
                    hasExplicitSleep -> sleepInsight = token
                    stressKeywords.any { lower.contains(it) } -> stressInsight = token
                    actKeywords.any { lower.contains(it) } -> activityInsight = token
                    vitalsKeywords.any { lower.contains(it) } -> vitalsInsight = token
                    sleepKeywords.any { lower.contains(it) } || REM_REGEX.containsMatchIn(token) -> sleepInsight = token
                }
            }

            // --- Time Token Extraction (e.g. "3:20 PM", "03:20", "3:20 p. m.") ---
            if (parsedWidgetTimestamp == null) {
                TIME_STRING_REGEX.find(token)?.let { match ->
                    var hour = match.groupValues[1].toInt()
                    val minute = match.groupValues[2].toInt()
                    var ampm = match.groupValues[3].trim()

                    if (ampm.isEmpty()) {
                        val nextToken = cleanTokens.getOrNull(i + 1)?.trim()
                        if (nextToken != null && AMPM_STANDALONE_REGEX.matches(nextToken)) {
                            ampm = nextToken
                        }
                    }

                    if (ampm.isNotEmpty()) {
                        val isPm = ampm.startsWith("p", ignoreCase = true)
                        val isAm = ampm.startsWith("a", ignoreCase = true)
                        if (isPm && hour in 1..11) {
                            hour += 12
                        } else if (isAm && hour == 12) {
                            hour = 0
                        }
                    }

                    try {
                        val now = ZonedDateTime.now(ZoneId.systemDefault())
                        var candidateTime = now.withHour(hour).withMinute(minute).withSecond(0).withNano(0)
                        if (candidateTime.isAfter(now.plusMinutes(2))) {
                            candidateTime = candidateTime.minusDays(1)
                        }
                        parsedWidgetTimestamp = candidateTime.toEpochSecond()
                        Log.i(TAG, "Parsed widget sample time from token '$token' (ampm='$ampm'): $parsedWidgetTimestamp ($candidateTime)")
                    } catch (e: Exception) {
                        Log.w(TAG, "Failed parsing widget time '$token': ${e.message}")
                    }
                }
            }

            // --- Composite contentDescription matches (e.g. "Sleep 88", "Battery 70%") ---
            COMPOSITE_SLEEP_REGEX.find(token)?.let {
                it.groupValues[1].toIntOrNull()?.let { score ->
                    if (score in 0..100) sleepScore = score
                }
            }
            COMPOSITE_ACT_REGEX.find(token)?.let {
                it.groupValues[1].toIntOrNull()?.let { score ->
                    if (score in 0..100) activityScore = score
                }
            }
            COMPOSITE_STRESS_REGEX.find(token)?.let {
                it.groupValues[1].toIntOrNull()?.let { score ->
                    if (score in 0..100) stressScore = score
                }
            }
            COMPOSITE_BAT_REGEX.find(token)?.let {
                it.groupValues[1].toIntOrNull()?.let { bat ->
                    if (bat in 1..100) ringBattery = bat
                }
            }

            // --- Standalone Headers & Value Pairs ---
            // In MediumHomeAppWidget, value might be immediately BEFORE or AFTER label
            // (e.g. ["88", "Sleep"] or ["Sleep", "88"])
            // Sleep Header
            if (lower == "sleep" || lower == "sueño") {
                val prev = cleanTokens.getOrNull(i - 1)
                val next = cleanTokens.getOrNull(i + 1)
                val prevNum = prev?.toIntOrNull()
                val nextNum = next?.toIntOrNull()
                if (prev == "--" || next == "--" || prevNum == 0 || nextNum == 0) {
                    sleepScore = 0
                } else if (prevNum != null && prevNum in 20..100) {
                    sleepScore = prevNum
                } else if (nextNum != null && nextNum in 20..100 && !next!!.startsWith("/")) {
                    sleepScore = nextNum
                }
            }

            // Stage Durations (Deep / REM / Light / Awake)
            if (lower == "deep" || lower == "profundo" || lower == "sueño profundo") {
                val candidate = cleanTokens.getOrNull(i + 1) ?: cleanTokens.getOrNull(i - 1)
                parseDurationMinutes(candidate)?.let { if (it in 1..600) parsedDeep = it }
            }
            if (lower == "rem" || lower == "fase rem") {
                val candidate = cleanTokens.getOrNull(i + 1) ?: cleanTokens.getOrNull(i - 1)
                parseDurationMinutes(candidate)?.let { if (it in 1..600) parsedRem = it }
            }
            if (lower == "light" || lower == "ligero" || lower == "sueño ligero") {
                val candidate = cleanTokens.getOrNull(i + 1) ?: cleanTokens.getOrNull(i - 1)
                parseDurationMinutes(candidate)?.let { if (it in 1..600) parsedLight = it }
            }
            if (lower == "awake" || lower == "despierto") {
                val candidate = cleanTokens.getOrNull(i + 1) ?: cleanTokens.getOrNull(i - 1)
                parseDurationMinutes(candidate)?.let { if (it in 1..300) parsedAwake = it }
            }

            // Activity Header
            if (lower == "activity" || lower == "actividad") {
                val prev = cleanTokens.getOrNull(i - 1)
                val next = cleanTokens.getOrNull(i + 1)
                val prevNum = prev?.toIntOrNull()
                val nextNum = next?.toIntOrNull()
                if (prev == "--" || next == "--" || prevNum == 0 || nextNum == 0) {
                    activityScore = 0
                } else if (prevNum != null && prevNum in 1..100) {
                    activityScore = prevNum
                } else if (nextNum != null && nextNum in 1..100 && !next!!.startsWith("/")) {
                    activityScore = nextNum
                }
            }

            // Stress Header
            if (lower == "stress" || lower == "estrés" || lower == "estres") {
                val prev = cleanTokens.getOrNull(i - 1)
                val next = cleanTokens.getOrNull(i + 1)
                val prevNum = prev?.toIntOrNull()
                val nextNum = next?.toIntOrNull()
                if (prev == "--" || next == "--") {
                    stressScore = 0
                } else if (prevNum != null && prevNum in 1..100) {
                    stressScore = prevNum
                } else if (nextNum != null && nextNum in 1..100 && !next!!.startsWith("/")) {
                    stressScore = nextNum
                }
            }

            // Battery Header
            if (lower == "battery" || lower == "batería" || lower == "bateria") {
                val next = cleanTokens.getOrNull(i + 1)
                val prev = cleanTokens.getOrNull(i - 1)
                if (next != null && next != "--" && !next.startsWith("/")) {
                    val num = next.replace("%", "").trim().toIntOrNull()
                    if (num != null && num in 1..100) ringBattery = num
                } else if (prev != null && prev != "--" && !prev.startsWith("/")) {
                    val num = prev.replace("%", "").trim().toIntOrNull()
                    if (num != null && num in 1..100) ringBattery = num
                }
            }

            // Heart Rate Header
            if (lower == "hr" || lower == "fc" || lower == "heart rate" || lower == "frecuencia cardíaca" || lower == "frecuencia cardiaca") {
                val candidates = listOfNotNull(cleanTokens.getOrNull(i + 1), cleanTokens.getOrNull(i + 2), cleanTokens.getOrNull(i - 1))
                for (cand in candidates) {
                    if (cand != "--" && !cand.startsWith("/")) {
                        val num = cand.replace("bpm", "").replace("lpm", "").trim().toIntOrNull()
                        if (num != null && num in 35..220) {
                            lastHr = num
                            break
                        }
                    }
                }
            }

            // Explicit Resting Heart Rate Header
            if (lower == "resting" || lower == "reposo" || lower == "en reposo" || lower == "resting hr" || lower == "fc reposo") {
                val candidates = listOfNotNull(cleanTokens.getOrNull(i + 1), cleanTokens.getOrNull(i + 2), cleanTokens.getOrNull(i - 1))
                for (cand in candidates) {
                    val num = cand.replace("bpm", "").replace("lpm", "").trim().toIntOrNull()
                    if (num != null && num in 35..150) {
                        avgHr = num
                        break
                    }
                }
            }

            // Explicit Latest Heart Rate Header
            if (lower.contains("última") || lower.contains("ultima") || lower.contains("latest") || lower.contains("actual") || lower.contains("current")) {
                val candidates = listOfNotNull(cleanTokens.getOrNull(i + 1), cleanTokens.getOrNull(i + 2), cleanTokens.getOrNull(i - 1))
                for (cand in candidates) {
                    val num = cand.replace("bpm", "").replace("lpm", "").trim().toIntOrNull()
                    if (num != null && num in 35..220) {
                        lastHr = num
                        break
                    }
                }
            }

            // SpO2 Header
            if (lower == "spo2" || lower == "blood oxygen" || lower == "oxígeno" || lower == "oxigeno") {
                val next = cleanTokens.getOrNull(i + 1)
                if (next != null && next != "--" && !next.startsWith("/")) {
                    val num = next.replace("%", "").trim().toIntOrNull()
                    if (num != null && num in 75..100) lastSpo2 = num
                }
            }

            // HRV Header
            if (lower == "hrv" || lower == "vfc" || lower == "variabilidad") {
                val next = cleanTokens.getOrNull(i + 1)
                if (next != null && next != "--" && !next.startsWith("/")) {
                    val num = next.replace("ms", "").trim().toIntOrNull()
                    if (num != null && num in 10..250) lastHrv = num
                }
            }

            // Individual units matching in DataIndicatorsWidget ([..., 70, bpm, 93, %, 59, ms])
            if (lower == "bpm" || lower == "lpm") {
                val prev = cleanTokens.getOrNull(i - 1)
                val num = prev?.replace(",", "")?.toIntOrNull()
                if (num != null && num in 35..220) lastHr = num
            }
            if (token == "%") {
                val prev = cleanTokens.getOrNull(i - 1)
                val num = prev?.replace(",", "")?.toIntOrNull()
                // If adjacent to ms or bpm, this is SpO2
                val next = cleanTokens.getOrNull(i + 1)
                val nextNext = cleanTokens.getOrNull(i + 2)
                if (num != null && num in 75..100 && (next == "ms" || nextNext == "ms" || cleanTokens.getOrNull(i - 2) == "bpm")) {
                    lastSpo2 = num
                }
            }
            if (lower == "ms") {
                val prev = cleanTokens.getOrNull(i - 1)
                val num = prev?.replace(",", "")?.toIntOrNull()
                if (num != null && num in 10..250) lastHrv = num
            }

            // Steps Header (strictly "steps" or "pasos", NEVER matching compound titles)
            if (lower == "steps" || lower == "pasos") {
                val next = cleanTokens.getOrNull(i + 1)
                if (next == "--") {
                    liveSteps = 0
                } else if (next != null && !next.startsWith("/")) {
                    val num = next.replace(",", "").replace(".", "").trim().toIntOrNull()
                    if (num != null && num in 0..150000) liveSteps = num
                }
                // Check for / targetSteps
                val candidateSlash = cleanTokens.getOrNull(i + 2)
                if (candidateSlash == "/") {
                    cleanTokens.getOrNull(i + 3)?.replace(",", "")?.replace(".", "")?.trim()?.toIntOrNull()?.let {
                        if (it in 1000..100000) targetSteps = it
                    }
                } else if (candidateSlash?.startsWith("/") == true) {
                    candidateSlash.removePrefix("/").replace(",", "").replace(".", "")?.trim()?.toIntOrNull()?.let {
                        if (it in 1000..100000) targetSteps = it
                    }
                }
            }

            // Calories Header (strictly "calories", "calories(kcal)", "calorías", "calorias", "calorías(kcal)", "kcal")
            // ONLY look forward immediately after the header; NEVER look backward (which holds target steps 6000)
            if (lower == "calories(kcal)" || lower == "calories" || lower == "calorías" || lower == "calorias" || lower == "calorías(kcal)" || lower == "kcal") {
                val next = cleanTokens.getOrNull(i + 1)
                if (next == "--") {
                    liveCalorie = 0
                } else if (next != null && !next.startsWith("/")) {
                    val num = next.replace(",", "").replace(".", "").trim().toIntOrNull()
                    if (num != null && num in 0..25000) liveCalorie = num
                }
                // Check for / targetCalorie
                val candidateSlash = cleanTokens.getOrNull(i + 2)
                if (candidateSlash == "/") {
                    cleanTokens.getOrNull(i + 3)?.replace(",", "")?.replace(".", "")?.trim()?.toIntOrNull()?.let {
                        if (it in 100..10000) targetCalorie = it
                    }
                } else if (candidateSlash?.startsWith("/") == true) {
                    candidateSlash.removePrefix("/").replace(",", "").replace(".", "")?.trim()?.toIntOrNull()?.let {
                        if (it in 100..10000) targetCalorie = it
                    }
                }
            }

            // Temperature Header & Values (e.g. "Skin Temperature", "Temperatura cutánea", "Temperatura de la piel")
            if (lower.contains("temperature") || lower.contains("temperatura") || lower.contains("cutánea") || lower.contains("cutanea") || lower.contains("skin temp") || lower.contains("piel")) {
                val candidates = listOfNotNull(
                    cleanTokens.getOrNull(i + 1),
                    cleanTokens.getOrNull(i + 2),
                    cleanTokens.getOrNull(i + 3),
                    cleanTokens.getOrNull(i - 1)
                )
                for (cand in candidates) {
                    SkinTemperatureGuard.offsetFrom(cand)?.let { skinTempOffset = it }
                }
            }

            // Standalone temperature offset (e.g. "+0.2°C", "-0.1°C", "+0,2 °C").
            // A bare integer is rejected: it is a step count far more often.
            SkinTemperatureGuard.offsetFrom(token)?.let { skinTempOffset = it }

            // Baseline temperature (e.g. "Baseline 36.1°C", "Línea base 36.1°C", "Línea base: 36,4 °C")
            if (lower == "baseline" || lower == "línea base" || lower == "linea base" || lower.contains("base")) {
                val candidates = listOfNotNull(
                    cleanTokens.getOrNull(i + 1),
                    cleanTokens.getOrNull(i + 2),
                    cleanTokens.getOrNull(i - 1)
                )
                for (cand in candidates) {
                    BASELINE_TEMP_REGEX.find(cand)?.let {
                        it.groupValues[1].replace(',', '.').toFloatOrNull()?.let { baseVal ->
                            if (SkinTemperatureGuard.isPlausibleBaseline(baseVal)) skinTempBaseline = baseVal
                        }
                    }
                }
            }
        }

        // 3. Fallbacks for HR and HRV on full text
        if (lastHr == 0) {
            HR_BPM_REGEX.find(fullText)?.let {
                val v = it.groupValues[1].toIntOrNull()
                if (v != null && v in 35..220) lastHr = v
            }
        }
        if (lastHrv == 0) {
            HRV_MS_REGEX.find(fullText)?.let {
                val v = it.groupValues[1].toIntOrNull()
                if (v != null && v in 10..250) lastHrv = v
            }
        }

        // Full text match for Baseline
        Regex("""(?i)\b(?:baseline|línea\s*base|linea\s*base)\s*:?\s*(3[4-9]\.\d{1,2}|40\.0)\s*°?C?\b""").find(fullText)?.let {
            it.groupValues[1].toFloatOrNull()?.let { baseVal ->
                if (SkinTemperatureGuard.isPlausibleBaseline(baseVal)) skinTempBaseline = baseVal
            }
        }

        // 4. Sleep Duration & Stages Reconciliation
        val foundDurations = mutableListOf<Int>()
        for (m in SLEEP_DURATION_REGEX.findAll(fullText)) {
            val h = m.groupValues[1].toIntOrNull() ?: 0
            val min = m.groupValues[2].toIntOrNull() ?: 0
            val total = h * 60 + min
            if (total in 60..840) {
                foundDurations.add(total)
            }
        }
        for (token in cleanTokens) {
            val d = parseDurationMinutes(token)
            if (d != null && d in 60..840 && !foundDurations.contains(d)) {
                foundDurations.add(d)
            }
        }

        if (parsedDeep > 0 || parsedRem > 0 || parsedLight > 0) {
            sleepDeepMins = parsedDeep
            sleepRemMins = parsedRem
            sleepLightMins = parsedLight
            if (parsedAwake > 0) sleepAwakeMins = parsedAwake
        } else if (foundDurations.isNotEmpty()) {
            val parsedSleepTotalMins = foundDurations.maxOrNull()!!
            val currentAsleep = sleepDeepMins + sleepRemMins + sleepLightMins
            if (currentAsleep == 0) {
                val deep = (parsedSleepTotalMins * 0.22).roundToInt()
                val rem = (parsedSleepTotalMins * 0.23).roundToInt()
                val light = parsedSleepTotalMins - deep - rem
                sleepDeepMins = deep
                sleepRemMins = rem
                sleepLightMins = light
            } else if (currentAsleep < parsedSleepTotalMins) {
                val factor = parsedSleepTotalMins.toDouble() / currentAsleep.toDouble()
                val scaledDeep = (sleepDeepMins * factor).roundToInt()
                val scaledRem = (sleepRemMins * factor).roundToInt()
                val scaledLight = parsedSleepTotalMins - scaledDeep - scaledRem
                sleepDeepMins = scaledDeep
                sleepRemMins = scaledRem
                sleepLightMins = scaledLight
            }
        }

        if (sleepScore == 0 && (sleepDeepMins + sleepRemMins + sleepLightMins) > 0) {
            val totalMins = sleepDeepMins + sleepRemMins + sleepLightMins
            val durScore = ((totalMins.toDouble() / 450.0).coerceAtMost(1.0) * 55.0)
            val deepScore = if (sleepDeepMins > 0) ((sleepDeepMins.toDouble() / 75.0).coerceAtMost(1.0) * 23.0) else 18.0
            val remScore = if (sleepRemMins > 0) ((sleepRemMins.toDouble() / 85.0).coerceAtMost(1.0) * 22.0) else 17.0
            val awakePenalty = (sleepAwakeMins.toDouble() / 12.0).coerceAtMost(12.0)
            sleepScore = (durScore + deepScore + remScore - awakePenalty).roundToInt().coerceIn(45, 98)
        }

        // 5. Midnight Rollover Guard: If widget timestamp belongs to a previous calendar day,
        // suppress daily-cumulative scores/counters from the unrefreshed yesterday widget snapshot.
        val todayEpochDay = ZonedDateTime.now(ZoneId.systemDefault()).toLocalDate().toEpochDay()
        val widgetSampleEpochDay = parsedWidgetTimestamp?.let { ts ->
            java.time.Instant.ofEpochSecond(ts).atZone(ZoneId.systemDefault()).toLocalDate().toEpochDay()
        }
        if (widgetSampleEpochDay != null && widgetSampleEpochDay < todayEpochDay) {
            Log.i(TAG, "Midnight Rollover Guard: Widget sample time is from previous day ($widgetSampleEpochDay < $todayEpochDay). Suppressing yesterday's cumulative widget counters.")
            liveSteps = baseVitals.liveSteps
            liveCalorie = baseVitals.liveCalorie
            activityScore = baseVitals.activityScore
            sleepScore = baseVitals.sleepScore
            sleepDeepMins = baseVitals.sleepDeepMins
            sleepRemMins = baseVitals.sleepRemMins
            sleepLightMins = baseVitals.sleepLightMins
            sleepAwakeMins = baseVitals.sleepAwakeMins
            sleepInsight = baseVitals.sleepInsight
            activityInsight = baseVitals.activityInsight
            stressInsight = baseVitals.stressInsight
            vitalsInsight = baseVitals.vitalsInsight
        }

        // 6. Sanitize liveCalorie if it was contaminated by targetSteps (e.g. 6000)
        if (liveCalorie >= targetSteps && targetSteps > 0 || (liveCalorie > 3000 && targetCalorie <= 1000)) {
            liveCalorie = if (liveSteps > 0) {
                (liveSteps * 0.045).roundToInt().coerceAtLeast(1)
            } else {
                0
            }
        }

        if (avgHr == 0) avgHr = lastHr
        if (avgSpo2 == 0) avgSpo2 = lastSpo2
        if (avgHrv == 0) avgHrv = lastHrv

        // No invented baseline: when the widget does not print one, the baseline
        // stays unknown instead of becoming 36.5 °C out of thin air.

        val result = baseVitals.copy(
            lastHeartRate = lastHr,
            avgHeartRate = avgHr,
            lastSpo2 = lastSpo2,
            avgSpo2 = avgSpo2,
            lastHrv = lastHrv,
            avgHrv = avgHrv,
            sleepScore = sleepScore,
            activityScore = activityScore,
            stressScore = stressScore,
            liveSteps = liveSteps,
            targetSteps = targetSteps,
            liveCalorie = liveCalorie,
            targetCalorie = targetCalorie,
            ringBattery = ringBattery,
            isConnected = true,
            refreshTimestamp = parsedWidgetTimestamp ?: (System.currentTimeMillis() / 1000L),
            sleepDeepMins = sleepDeepMins,
            sleepRemMins = sleepRemMins,
            sleepLightMins = sleepLightMins,
            sleepAwakeMins = sleepAwakeMins,
            skinTempOffset = skinTempOffset,
            skinTempBaseline = skinTempBaseline,
            sleepInsight = sleepInsight,
            stressInsight = stressInsight,
            activityInsight = activityInsight,
            vitalsInsight = vitalsInsight
        )

        Log.d(TAG, "Parsed telemetry from ${cleanTokens.size} tokens: HR=$lastHr, SpO2=$lastSpo2, HRV=$lastHrv, Sleep=$sleepScore, Act=$activityScore, Stress=$stressScore, Steps=$liveSteps, Cal=$liveCalorie, Bat=$ringBattery, TempOffset=$skinTempOffset, TempBase=$skinTempBaseline, Insights=[Sleep=${sleepInsight.isNotBlank()}, Stress=${stressInsight.isNotBlank()}, Act=${activityInsight.isNotBlank()}, Vit=${vitalsInsight.isNotBlank()}]")
        return result
    }
